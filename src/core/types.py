"""
Core data contracts and domain types for TriQuery.
Used across engines, query planner, result fusion, and explainability modules.
"""

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class EngineType(str, Enum):
    """Supported underlying query engines."""
    RELATIONAL = "relational"
    GRAPH = "graph"
    VECTOR = "vector"
    HYBRID = "hybrid"


class EngineExecutionMetadata(BaseModel):
    """Metadata recorded during single-engine execution."""
    engine: EngineType
    execution_time_ms: float
    record_count: int
    query_executed: str
    notes: List[str] = Field(default_factory=list)


class EngineResult(BaseModel):
    """Output contract for any individual engine."""
    engine: EngineType
    success: bool
    data: List[Dict[str, Any]]
    metadata: EngineExecutionMetadata
    error: Optional[str] = None


class QueryPlanStep(BaseModel):
    """Represents one planned execution step in the query pipeline."""
    step_id: int
    engine: EngineType
    description: str
    target_operation: str
    parameters: Dict[str, Any] = Field(default_factory=dict)
    depends_on_steps: List[int] = Field(default_factory=list)


class QueryPlan(BaseModel):
    """Full execution plan generated by the TriQuery Query Planner."""
    query_id: str
    natural_query: str
    required_engines: List[EngineType]
    steps: List[QueryPlanStep]
    estimated_cost_note: str = ""


class UnifiedRecord(BaseModel):
    """Fused record combining attributes and relevance scores from multiple engines."""
    entity_id: str
    entity_type: str
    title: str
    attributes: Dict[str, Any] = Field(default_factory=dict)
    relational_matched: bool = False
    graph_matched: bool = False
    vector_score: Optional[float] = None
    final_rank_score: float = 0.0
    reason_for_inclusion: str = ""


class QueryExplanation(BaseModel):
    """Explainability report for viva defense and user inspection."""
    query_id: str
    query_text: str
    engines_used: List[EngineType]
    total_execution_time_ms: float
    engine_timings: Dict[str, float]
    intermediate_counts: Dict[str, int]
    plan_explanation: str
    ranking_explanation: str
    records: List[UnifiedRecord]


